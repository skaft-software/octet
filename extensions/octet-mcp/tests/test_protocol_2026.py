    def test_dispatch_guard_fences_every_mrtr_round_after_connect(self):
        for method in ("tools/call", "resources/read"):
            connected = []
            guarded = []
            def respond(request):
                message = request.message()
                if message["method"] == "server/discover":
                    return _json_result(request, {**DISCOVERY, "capabilities": {"tools": {}, "resources": {}}})
                if message["method"] == "tools/list":
                    return _json_result(request, {"tools": [annotated_tool()]})
                return _json_result(request, {"resultType": "input_required", "requestState": "opaque"})
            client, fixture = self.client(respond)
            client.start()
            client.list_tools()
            original_connection = client._connection
            def connection(operation, deadline):
                connection = original_connection(operation, deadline)
                original_connect = connection.connect
                def connect():
                    original_connect()
                    connected.append(True)
                connection.connect = connect
                return connection
            def guard():
                # This must run after DNS/TCP/TLS, not just at manager admission.
                self.assertEqual(len(connected), len(guarded) + 1)
                guarded.append(True)
                if len(guarded) == 2:
                    raise McpError("retired_catalog", "Approved catalog was retired during connection setup")
            with patch.object(client, "_connection", side_effect=connection):
                with self.assertRaises(McpError) as error:
                    if method == "tools/call":
                        client.call_tool("echo", {"value": "once"}, dispatch_guard=guard)
                    else:
                        client.request(method, {"uri": "opaque:ref"}, timeout_ms=1000, dispatch_guard=guard)
            self.assertEqual(error.exception.code, "retired_catalog")
            self.assertEqual(len(guarded), 2)
            self.assertEqual(len(connected), 2)
            # The continuation was never sent, despite completing its connection.
            self.assertEqual([request.message()["method"] for request in fixture.requests], ["server/discover", "tools/list", method])


