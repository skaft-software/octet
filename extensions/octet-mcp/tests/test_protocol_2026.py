def annotated_tool():
    tool = _tool()
    tool["inputSchema"]["properties"]["value"]["x-mcp-header"] = "Value"
    return tool


def error_reply(request, code, *, status=400, data=None, request_id=None):
    error = {"code": code, "message": "UNTRUSTED secret remote error"}
    if data is not None:
        error["data"] = data
    return _HttpReply(
        status=status, headers={"Content-Type": "application/json"},
        body=_json_bytes({"jsonrpc": "2.0", "id": request.message()["id"] if request_id is None else request_id, "error": error}),
    )


class HeaderMetadataTests(unittest.TestCase):
    def test_exact_spec_header_encoding_examples(self):
        for value, expected in (
            ("us-west1", "us-west1"),
            ("Hello, 世界", "=?base64?SGVsbG8sIOS4lueVjA==?="),
            (" padded ", "=?base64?IHBhZGRlZCA=?="),
            ("line1\nline2", "=?base64?bGluZTEKbGluZTI=?="),
            ("=?base64?literal?=", "=?base64?PT9iYXNlNjQ/bGl0ZXJhbD89?="),
            ("", ""), ("a\tb", "a\tb"), ("\tx", "=?base64?CXg=?="),
        ):
            with self.subTest(value=value):
                self.assertEqual(encode_header_value(value), expected)

    def test_nested_primitive_extraction_null_omission_and_safe_integers(self):
        parameters = header_parameters({"properties": {"nested": {"properties": {
            "s": {"type": "string", "x-mcp-header": "S"},
            "n": {"type": "integer", "x-mcp-header": "N"},
            "b": {"type": "boolean", "x-mcp-header": "B"},
        }}}})
        headers = request_headers("tools/call", {"name": " t ", "arguments": {"nested": {"s": None, "n": 42.0, "b": False}}}, parameters)
        self.assertEqual(headers, {
            "MCP-Protocol-Version": "2026-07-28", "Mcp-Method": "tools/call",
            "Mcp-Name": "=?base64?IHQg?=", "Mcp-Param-N": "42", "Mcp-Param-B": "false",
        })
        for value in (MAX_SAFE_INTEGER + 1, -MAX_SAFE_INTEGER - 1, True, 1.5, "4"):
            with self.subTest(value=value), self.assertRaises(McpProtocolError):
                request_headers("tools/call", {"name": "t", "arguments": {"nested": {"n": value}}}, parameters)
        self.assertNotIn("Mcp-Param-S", request_headers("tools/call", {"name": "t", "arguments": {}}, parameters))

    def test_header_annotations_reject_unsafe_names_types_and_reachability(self):
        leaf = {"type": "string", "x-mcp-header": "Tenant"}
        schemas = [
            leaf,
            {"properties": {"x": {**leaf, "x-mcp-header": "bad\r\nInjected"}}},
            {"properties": {"x": {**leaf, "x-mcp-header": ""}}},
            {"properties": {"x": {**leaf, "type": "number"}}},
            {"properties": {"x": {**leaf, "type": ["string", "null"]}}},
            {"properties": {"x": leaf, "y": {**leaf, "x-mcp-header": "tenant"}}},
            {"properties": {"x": {"items": {"properties": {"y": leaf}}}}},
            {"allOf": [{"properties": {"x": leaf}}]},
            {"additionalProperties": {"properties": {"x": leaf}}},
            {"$defs": {"x": leaf}, "properties": {"x": {"$ref": "#/$defs/x"}}},
            {"$defs": {"unused": {"properties": {"x": leaf}}}},
        ]
        for schema in schemas:
            with self.subTest(schema=schema), self.assertRaises(CatalogError):
                header_parameters(schema)
        # Literal annotation-looking data in enum/const is not a schema node.
        self.assertEqual(header_parameters({"properties": {"x": {"const": {"x-mcp-header": "data"}}}}), ())

    def test_header_value_and_aggregate_budgets_reject_without_truncation(self):
        with self.assertRaises(McpProtocolError):
            encode_header_value("x" * (MAX_MIRRORED_HEADER_BYTES + 1))
        parameters = header_parameters({"properties": {
            "a": {"type": "string", "x-mcp-header": "A"},
            "b": {"type": "string", "x-mcp-header": "B"},
        }})
        with self.assertRaises(McpProtocolError):
            request_headers("tools/call", {"name": "t", "arguments": {"a": "a" * 9000, "b": "b" * 9000}}, parameters)

    def test_ref_sibling_headers_retain_raw_and_published_provenance(self):
        schema = {
            "properties": {"value": {
                "$ref": "#/$defs/bounded", "type": "string", "x-mcp-header": "Value",
                "allOf": [{"minLength": 1}],
            }},
            "$defs": {"bounded": {"type": "string", "maxLength": 3}},
        }
        self.assertEqual(header_parameters(schema), header_parameters(normalize_schema(schema, require_object=True)))
        # A $ref cannot erase an invalid original placement or duplicate name.
        for bad in (
            {"$defs": {"hidden": {"properties": {"x": {"type": "string", "x-mcp-header": "X"}}}}, "$ref": "#/$defs/hidden"},
            {"properties": {"a": {"type": "string", "x-mcp-header": "X"}, "nested": {"properties": {"b": {"type": "string", "x-mcp-header": "x"}}}}},
        ):
            with self.assertRaises(CatalogError):
                header_parameters(bad)

    def test_header_count_budget_and_prefix_cannot_override_protocol_or_credentials(self):
        with self.assertRaises(CatalogError):
            header_parameters({"properties": {f"p{i}": {"type": "string", "x-mcp-header": f"P{i}"} for i in range(62)}})
        parameters = header_parameters({"properties": {"value": {"type": "string", "x-mcp-header": "Authorization"}}})
        headers = request_headers("tools/call", {"name": "echo", "arguments": {"value": "untrusted"}}, parameters)
        self.assertNotIn("Authorization", headers)
        self.assertEqual(headers["Mcp-Param-Authorization"], "untrusted")
        self.assertEqual(headers["MCP-Protocol-Version"], "2026-07-28")


class ModernHttpTests(unittest.TestCase):
    def setUp(self):
        self.fixtures = []
        self.clients = []

    def tearDown(self):
        for client in reversed(self.clients):
            client.close()
        for fixture in reversed(self.fixtures):
            fixture.close()
            self.assertEqual(fixture.errors, ())

    def client(self, responder, *, config_changes=None, bridge_limits=None, **kwargs):
        fixture = _LoopbackFixture(responder)
        self.fixtures.append(fixture)
        config = replace(_remote_config(fixture.url), protocol_version=MCP_PROTOCOL_VERSION_2026, **(config_changes or {}))
        client = McpHttp2026Client(config, bridge_limits or limits(), **kwargs)
        self.clients.append(client)
        return client, fixture

    def responder(self, tool_reply=None, *, tools=None, discovery=None):
        def respond(request):
            message = request.message()
            if message["method"] == "server/discover":
                return _json_result(request, DISCOVERY if discovery is None else discovery)
            if message["method"] == "tools/list":
                return _json_result(request, {"resultType": "complete", "tools": tools if tools is not None else [annotated_tool()]})
            if message["method"] == "tools/call" and tool_reply is not None:
                return tool_reply(request)
            raise AssertionError("unexpected modern request")
        return respond

    def test_explicit_mode_is_required_and_legacy_constants_are_unchanged(self):
        from octet_mcp.protocol import MCP_PROTOCOL_VERSION, SUPPORTED_PROTOCOL_VERSIONS
        self.assertEqual(MCP_PROTOCOL_VERSION, "2025-06-18")
        self.assertNotIn(MCP_PROTOCOL_VERSION_2026, SUPPORTED_PROTOCOL_VERSIONS)
        with self.assertRaises(ValueError):
            McpHttp2026Client(_remote_config("http://127.0.0.1:1/mcp"), limits())
        self.assertTrue(issubclass(McpHttp2026Client, McpStreamableHttpClient))

