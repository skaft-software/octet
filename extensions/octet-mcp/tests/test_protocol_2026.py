        phase = [0]
        old = annotated_tool()["inputSchema"]
        newer = copy.deepcopy(old)
        newer["properties"]["value"]["x-mcp-header"] = "New"
        def respond(request):
            method = request.message()["method"]
            if method == "server/discover":
                return _json_result(request, DISCOVERY)
            if method == "tools/list":
                return _json_result(request, {"tools": [{**annotated_tool(), "inputSchema": old if phase[0] == 0 else newer}]})
            barrier.wait(2)
            params = request.message()["params"]
            state = "state-" + params["arguments"]["value"]
            if "requestState" not in params:
                return _json_result(request, {"resultType": "input_required", "requestState": state})
            self.assertEqual(params["requestState"], state)
            return _json_result(request, {"content": []})
        client, fixture = self.client(respond)
        client.start()
        client.list_tools()
        pinned = normalize_schema(old, require_object=True)
        phase[0] = 1
        client.list_tools()
        errors = []
        def call(value, schema):
            try:
                client.call_tool("echo", {"value": value}, input_schema=schema)
            except BaseException as error:
                errors.append(error)
        workers = [threading.Thread(target=call, args=("old", pinned)), threading.Thread(target=call, args=("new", None))]
        for worker in workers:
            worker.start()
        for worker in workers:
            worker.join(3)
        self.assertEqual(errors, [])
        calls = {request.message()["params"]["arguments"]["value"]: request for request in fixture.requests if request.message()["method"] == "tools/call"}
        self.assertEqual(calls["old"].header("Mcp-Param-Value"), "old")
        self.assertIsNone(calls["old"].header("Mcp-Param-New"))
        self.assertEqual(calls["new"].header("Mcp-Param-New"), "new")
